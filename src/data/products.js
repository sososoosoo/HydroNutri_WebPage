export const discountRate = (listPrice, price) =>
  listPrice > price ? Math.round(((listPrice - price) / listPrice) * 100) : 0;

export const formatKRW = (value) => value.toLocaleString('ko-KR');

export const findProduct = (id) => {
  const key = String(id);
  const item =
    cosmetics.find((p) => String(p.id) === key) ||
    ingredients.find((p) => String(p.id) === key);
  if (!item) return null;
  return {
    ...item,
    category: cosmetics.includes(item) ? 'cosmetics' : 'ingredients',
  };
};
